#!/usr/bin/env python3
"""make_stage2_final.py -- build the two X2b Stage-2 configs (Anna 2026-11-12) from stage2_fv4.jsonc + the vocab agents' keys.

  A = runconfigs/overnight_20261111/stage2_final_A.jsonc: fv4 (fanout_v2.vocab_rj rmw+jmp) + the ilv-vocab key + the abs-vocab
      table, chain interleaving OFF (comparable with fv3).
  B = runconfigs/overnight_20261111/stage2_final_B.jsonc: A + chain interleaving ON (NEW, never-evaluated recipe): the chain block of
      runconfigs/run_config_STT_6_interleave.jsonc (free_pool reg 5 / mem 3, chain length 2-4, step_kinds other_n/ld/str,
      num_chains 1) with variants_per_instance 1 instead of 4, because the streaming Stage 2 (stage2_sharded.py, stream_fp.py) keys
      every test on <stem>.ll / <stem>.ann.json and would never see <stem>_v<k> files; one interleaved test per program also keeps
      B's test count equal to A's.

The vocab agents' keys come from --keys <json>, written when ilv-vocab and abs-vocab are both DONE in claudenotes.md:
  {"instruction_tables": "<abs-vocab table path>",            (replaces paths.instruction_tables)
   "merge": {<top-level key>: <value>, ...},                   (e.g. the ilv-vocab key; deep-merged into the config)
   "interleave_merge": {...}}                                   (B only, e.g. step kinds drawn from the interleave-only category)
Refuses to run without --keys (no guessed values). Usage:
  python3 scripts/overnight_20261111/make_stage2_final.py --keys runconfigs/overnight_20261111/vocab_keys.json
"""
import argparse, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "runconfigs/overnight_20261111"


def load(p):
    t = Path(p).read_text()
    return json.loads(re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", t, flags=re.S)))


def merge(a, b):
    for k, v in b.items():
        if isinstance(v, dict) and isinstance(a.get(k), dict):
            merge(a[k], v)
        else:
            a[k] = v
    return a


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--keys", required=True); a = ap.parse_args()
    keys = load(a.keys)
    base = load(D / "stage2_fv4.jsonc")
    A = json.loads(json.dumps(base))
    if keys.get("instruction_tables"):
        A["paths"]["instruction_tables"] = keys["instruction_tables"]
    merge(A, keys.get("merge", {}))
    A["interleave"] = {"enabled": False}
    A["paths"]["results_name"] = "stage2_final_A"
    B = json.loads(json.dumps(A))
    il = load(ROOT / "runconfigs/run_config_STT_6_interleave.jsonc")["interleave"]
    il["variants_per_instance"] = 1
    B["interleave"] = merge(il, keys.get("interleave_merge", {}))
    B["paths"]["results_name"] = "stage2_final_B"
    # SPT variants (protcheck 2026-11-12, DECIDE SPT-VOCAB): gem5-spt backward-untaints through invertible ops on the data path,
    # which SPT_6_u's InvOp does not express -> no value-neutral splices and no invertible abstract forms (inc, cmov_rr, ...).
    # Fillers (dead destination register, never read) and jmp fillers stay. Table: keys["spt_instruction_tables"] (abs-vocab's
    # table with invertible forms excluded), else the base instructions.jsonc (no inc / cmov_rr).
    outs = []
    for name, cfg in (("A", A), ("B", B)):
        sp = json.loads(json.dumps(cfg))
        sp["fanout_v2"]["splice"]["enabled"] = False
        sp["paths"]["instruction_tables"] = keys.get("spt_instruction_tables") or "STAGE2_compilation/instruction_tables/instructions.jsonc"
        sp["paths"]["results_name"] = f"stage2_final_{name}_spt"
        outs.append((f"{name}_spt", sp, f"SPT variant of {name}: splices off, table {sp['paths']['instruction_tables']} (no invertible forms; DECIDE SPT-VOCAB)"))
    src = f"stage2_fv4.jsonc + {a.keys}"
    for name, cfg, note in (("A", A, "fillers-only (fv4 + ilv-vocab key + abs-vocab table), chain interleaving off; comparable with fv3"),
                            ("B", B, "NEW, NEVER-EVALUATED recipe: A + chain interleaving on (run_config_STT_6_interleave.jsonc chain block, "
                                     "variants_per_instance 1)")) + tuple(outs):
        (D / f"stage2_final_{name}.jsonc").write_text(
            f"// overnight X2b Stage-2 config {name} (generated by scripts/overnight_20261111/make_stage2_final.py from {src}): {note}.\n"
            + json.dumps(cfg, indent=2) + "\n")
        print("wrote", D / f"stage2_final_{name}.jsonc")


if __name__ == "__main__":
    main()
