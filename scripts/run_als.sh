#!/usr/bin/env bash
# run_als.sh — run the SimSpect pipeline on any .als file, with all output under build/ (git-ignored).
#
# Usage: scripts/run_als.sh <path/to/Model.als> [base_config.jsonc] [phase]
#   base_config  default runconfigs/regen_lp_20261110/stage2_fv3.jsonc (the Stage-2 recipe v3)
#   phase        gen (default: testsetgen.py, xml+llvm+asm streamed, no gem5)
#                or any pipeline.py phase: xml | llvm | asm | gem5 | all | clean
#
# Writes build/configs/<Model>.jsonc = the base config with paths.models_dir set to the .als's
# directory and paths.testset_dir / paths.results_dir set to build/testsets / build/results, then
# calls the existing entry point with it. Output: build/testsets/<Model>/ (and build/results/ for
# pipeline.py gem5/all). testrun.py always writes to results/, so it is not wrapped here.
set -euo pipefail

[ $# -ge 1 ] || { sed -n '2,12p' "$0"; exit 2; }
ALS="$1"; BASE="${2:-runconfigs/regen_lp_20261110/stage2_fv3.jsonc}"; PHASE="${3:-gen}"
[ -f "$ALS" ] || { echo "error: no such .als: $ALS" >&2; exit 1; }
case "$ALS" in *.als) ;; *) echo "error: not a .als file: $ALS" >&2; exit 1 ;; esac

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ALS_DIR="$(cd "$(dirname "$ALS")" && pwd)"
STEM="$(basename "$ALS" .als)"
case "$BASE" in /*) ;; *) BASE="$REPO/$BASE" ;; esac
[ -f "$BASE" ] || { echo "error: no such config: $BASE" >&2; exit 1; }

BUILD="$REPO/build"
CFG="$BUILD/configs/$STEM.jsonc"
mkdir -p "$BUILD/configs" "$BUILD/testsets" "$BUILD/results"

cd "$REPO"
python3 - "$BASE" "$CFG" "$ALS_DIR" "$BUILD" "$STEM" <<'EOF'
import json, sys
from pathlib import Path
sys.path.insert(0, ".")
from pipeline import load_config
base, out, als_dir, build, stem = sys.argv[1:]
cfg = load_config(Path(base))
p = cfg.setdefault("paths", {})
p["models_dir"] = als_dir
p["testset_dir"] = f"{build}/testsets"
p["results_dir"] = f"{build}/results"
p["results_name"] = stem
hdr = f"// generated by scripts/run_als.sh from {base}\n"
Path(out).write_text(hdr + json.dumps(cfg, indent=2) + "\n")
print(f"[run_als] config: {out}")
EOF

if [ "$PHASE" = "gen" ]; then
  exec python3 testsetgen.py --model "$STEM" --config "$CFG"
else
  exec python3 pipeline.py "$PHASE" --model "$STEM" --config "$CFG"
fi
