#!/usr/bin/env python3
"""make_firstdet_fig_v2.py: write the v2 first-detection bar figure (firstdet-final, 2026-11-10) from a
firstdet_report.py JSON. NEW files only (paper rule: never overwrite an existing paper file):
  <tikz>/firstdet_bars_v2_body.tex, <tikz>/firstdet_bars_v2_8pt.tex, <tikz>/_standalone_firstdet_bars_v2.tex
then compiles the standalone and renders <tikz>/_standalone_firstdet_bars_v2-1.png (pdflatex + pdftoppm).
Layout = firstdet_bars_body.tex (same colors, 8pt, log axis) with six groups: UV1 | UV3 UV4 UV5 | UV6 jmp*.
A bug with K=0 is drawn as a hatched SimSpect bar at N+1 labelled "> N" (a lower bound on SimSpect's cost,
so its ratio is an upper bound, printed with a leading "<").

    python3 make_firstdet_fig_v2.py report.json --tikz ~/trippel/ISCA-27/tikz [--note "..."] [--force]
"""
import argparse, json, math, subprocess, sys
from pathlib import Path

BUGS = ["UV1", "UV3", "UV4", "UV5", "UV6", "jmp_shadow"]
LABEL = {"jmp_shadow": "{jmp$^{*}$}"}


def fmt_ratio(r):
    if r >= 100:
        s = f"{int(round(r, -int(math.floor(math.log10(r))) + 1)):,}".replace(",", "{,}")
    elif r >= 10:
        s = f"{r:.0f}"
    else:
        s = f"{r:.1f}"
    return s + "$\\times$"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("report")
    ap.add_argument("--tikz", default=str(Path.home() / "trippel/ISCA-27/tikz"))
    ap.add_argument("--note", default="")
    ap.add_argument("--force", action="store_true", help="overwrite the v2 files (only files this script created)")
    a = ap.parse_args()
    rep = json.loads(Path(a.report).read_text())
    tikz = Path(a.tikz)
    names = ["firstdet_bars_v2_body.tex", "firstdet_bars_v2_8pt.tex", "_standalone_firstdet_bars_v2.tex"]
    for n in names:
        p = tikz / n
        if p.exists() and not a.force:
            sys.exit(f"{p} exists; pass --force only if this script wrote it")
    rows, vals = [], []
    for i, b in enumerate(BUGS):
        v = rep["bugs"][b]
        s = math.log10(v["expected_tests"])
        am = math.log10(v["amulet_pooled_test_cases"])
        r = fmt_ratio(v["multiple_tests"])
        if v["censored"]:
            r = "$<$" + r
        hatch = 1 if v["censored"] else 0
        rows.append(f"  {i}/{s:.4f}/{am:.4f}/{{{r}}}/{LABEL.get(b, b)}/{hatch}")
        vals.append(f"{b} {'>' if v['censored'] else ''}{v['expected_tests']} (K {v['K']}/{v['N']}) vs "
                    f"{v['amulet_pooled_test_cases']:,}")
    m = rep.get("minimum", {}).get("tests", {})
    body = f"""% Tests to first detection per bug, SimSpect vs AMuLeT, log scale, v2 (body only; used by firstdet_bars_v2_8pt.tex and _standalone_firstdet_bars_v2.tex).
% Generated by simspect STAGE3_gem5/timing/make_firstdet_fig_v2.py from {Path(a.report).name} (firstdet-final, 2026-11-10). {a.note}
% Data: simspect wiki/state/EVAL_MANIFEST.md "Footprint model: the unified AMuLeT-comparison experiment" (Results).
% SimSpect = expected tests to first detection (N+1)/(K+1) on ONE corpus (Footprint_6_u core lpP fv3) for all three defenses,
% AMuLeT's exact configs, per-test random cache setup (warm/cold/full where the build allows) and random branch stalls.
% AMuLeT = pooled test cases (program x input) per violation of that bug, 32 instances x 200 programs x 140 inputs.
% Hatched bar = not found in N tests (drawn at N+1; the ratio is an upper bound). Every text is \\footnotesize (8pt).
% values: {'; '.join(vals)}; minimum over the five known bugs: {m.get('multiple')}x ({m.get('bug')})
\\begin{{tikzpicture}}[font=\\footnotesize, x=1cm, y=1cm]
\\definecolor{{fdsim}}{{RGB}}{{158,202,225}}% light blue: SimSpect
\\definecolor{{fdamu}}{{RGB}}{{217,217,217}}% light gray: AMuLeT
\\def\\fdu{{0.42}}% cm per decade
\\def\\fdoff{{0.30}}% log10 offset so a value of 1 test still shows
\\def\\fdbw{{0.26}}% bar width, cm
\\def\\fdgap{{1.12}}% group pitch, cm
\\def\\fdn{{6}}% groups
\\foreach \\e/\\lab in {{0/1, 1/10, 2/10^2, 3/10^3, 4/10^4, 5/10^5, 6/10^6}} {{
  \\draw[black!12] (0, {{(\\e+\\fdoff)*\\fdu}}) -- ({{\\fdn*\\fdgap+0.15}}, {{(\\e+\\fdoff)*\\fdu}});
  \\draw (0, {{(\\e+\\fdoff)*\\fdu}}) -- (-0.06, {{(\\e+\\fdoff)*\\fdu}}) node[left, inner sep=1pt] {{$\\lab$}};
}}
\\draw (0,0) -- (0, {{(6.2+\\fdoff)*\\fdu}});
\\draw (0,0) -- ({{\\fdn*\\fdgap+0.15}}, 0);
\\node[rotate=90, anchor=south] at (-0.62, {{(3+\\fdoff)*\\fdu}}) {{tests per detection (log)}};
% bars: index / log10(SimSpect) / log10(AMuLeT) / ratio label / x label / hatched (K=0)
\\foreach \\i/\\s/\\a/\\r/\\la/\\hh in {{
{(','+chr(10)).join(rows)}}} {{
  \\pgfmathsetmacro{{\\xc}}{{0.58+\\i*\\fdgap}}
  \\pgfmathsetmacro{{\\hs}}{{(\\s+\\fdoff)*\\fdu}}
  \\pgfmathsetmacro{{\\ha}}{{(\\a+\\fdoff)*\\fdu}}
  \\fill[fdsim] ({{\\xc-\\fdbw-0.01}}, 0) rectangle ({{\\xc-0.01}}, \\hs);
  \\ifnum\\hh=1 \\fill[pattern=north east lines, pattern color=black!55] ({{\\xc-\\fdbw-0.01}}, 0) rectangle ({{\\xc-0.01}}, \\hs); \\fi
  \\draw ({{\\xc-\\fdbw-0.01}}, 0) rectangle ({{\\xc-0.01}}, \\hs);
  \\fill[fdamu] ({{\\xc+0.01}}, 0) rectangle ({{\\xc+\\fdbw+0.01}}, \\ha);
  \\draw ({{\\xc+0.01}}, 0) rectangle ({{\\xc+\\fdbw+0.01}}, \\ha);
  \\node[anchor=south, inner sep=1.5pt] at (\\xc, {{max(\\hs,\\ha)}}) {{\\r}};
  \\node[anchor=north, inner sep=1.5pt] at (\\xc, -0.02) {{\\la}};
}}
\\node[anchor=north, inner sep=1.5pt] at ({{0.58+0*\\fdgap}}, -0.36) {{InvisiSpec}};
\\node[anchor=north, inner sep=1.5pt] at ({{0.58+2*\\fdgap}}, -0.36) {{CleanupSpec}};
\\node[anchor=north, inner sep=1.5pt] at ({{0.58+4.5*\\fdgap}}, -0.36) {{SpecLFB}};
\\draw[black!45] ({{0.58+1*\\fdgap-0.32}}, -0.40) -- ({{0.58+3*\\fdgap+0.32}}, -0.40);
\\draw[black!45] ({{0.58+4*\\fdgap-0.32}}, -0.40) -- ({{0.58+5*\\fdgap+0.32}}, -0.40);
\\draw[black!45, dashed] ({{0.58+4.5*\\fdgap}}, 0) -- ({{0.58+4.5*\\fdgap}}, {{(6.2+\\fdoff)*\\fdu}});
\\fill[fdsim] (0.25, {{(6.55+\\fdoff)*\\fdu}}) rectangle (0.50, {{(6.85+\\fdoff)*\\fdu}});
\\draw (0.25, {{(6.55+\\fdoff)*\\fdu}}) rectangle (0.50, {{(6.85+\\fdoff)*\\fdu}});
\\node[anchor=west, inner sep=2pt] at (0.52, {{(6.7+\\fdoff)*\\fdu}}) {{SimSpect tests}};
\\fill[fdamu] (3.05, {{(6.55+\\fdoff)*\\fdu}}) rectangle (3.30, {{(6.85+\\fdoff)*\\fdu}});
\\draw (3.05, {{(6.55+\\fdoff)*\\fdu}}) rectangle (3.30, {{(6.85+\\fdoff)*\\fdu}});
\\node[anchor=west, inner sep=2pt] at (3.32, {{(6.7+\\fdoff)*\\fdu}}) {{AMuLeT test cases}};
\\end{{tikzpicture}}%
"""
    fig = f"""% Results figure v2, 8pt (every text \\footnotesize): tests to first detection per bug, SimSpect vs AMuLeT, log scale.
% Body in tikz/firstdet_bars_v2_body.tex; preview tikz/_standalone_firstdet_bars_v2-1.png. Use with \\input{{tikz/firstdet_bars_v2_8pt}}.
% Needs \\usetikzlibrary{{patterns}} in the preamble (hatched bars for bugs not found).
\\begin{{figure}}[t]
\\centering
\\input{{tikz/firstdet_bars_v2_body}}
\\caption{{Tests to the first detection of each previously known bug, and of the new jmp-shadow bug (jmp$^{{*}}$), on a log scale. \\toolname{{}}: expected tests to the first detection over a random order of one test corpus shared by all three defenses, at AMuLeT's exact configurations, with each test's cache start (hot, flushed, or a filled L1D, as the build allows) and branch-resolution delays drawn at random. AMuLeT: test cases (one program on one input) per detection of that bug, over 32 runs of its own fuzzer with its own settings. Labels give the ratio; a hatched bar was not found in the tests run.}}
\\label{{fig:firstdet}}
\\end{{figure}}
"""
    sa = """\\documentclass[border=4pt,10pt]{standalone}
\\usepackage{tikz,xcolor}
\\usetikzlibrary{patterns}
\\begin{document}
\\input{firstdet_bars_v2_body}
\\end{document}
"""
    (tikz / names[0]).write_text(body)
    (tikz / names[1]).write_text(fig)
    (tikz / names[2]).write_text(sa)
    p = subprocess.run(["pdflatex", "-interaction=nonstopmode", names[2]], cwd=tikz, capture_output=True, text=True)
    if p.returncode:
        sys.exit("pdflatex failed:\n" + p.stdout[-3000:])
    subprocess.run(["pdftoppm", "-png", "-r", "300", "-singlefile", "_standalone_firstdet_bars_v2.pdf",
                    "_standalone_firstdet_bars_v2-1"], cwd=tikz, check=True)
    for ext in (".aux", ".log", ".pdf"):
        (tikz / f"_standalone_firstdet_bars_v2{ext}").unlink(missing_ok=True)
    print("wrote", *[tikz / n for n in names], tikz / "_standalone_firstdet_bars_v2-1.png")


if __name__ == "__main__":
    main()
